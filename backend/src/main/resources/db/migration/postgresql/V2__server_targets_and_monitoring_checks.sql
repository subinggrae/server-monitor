-- Server Target과 Monitoring Check (PostgreSQL)
--
-- Server Target은 사용자가 관리하는 모니터링 대상 서버입니다.
-- Monitoring Check는 그 서버에 대해 실행하는 가용성 확인입니다.
--
-- mariadb/V2__server_targets_and_monitoring_checks.sql과 논리 Schema가 같아야 합니다.

CREATE TABLE server_targets (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR(100) NOT NULL,
    host        VARCHAR(255) NOT NULL,
    environment VARCHAR(50)  NOT NULL,
    description VARCHAR(500) NULL,
    enabled     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP(6) NOT NULL,
    updated_at  TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    -- 목록에서 서버를 구분할 수 있도록 이름은 중복을 막습니다.
    CONSTRAINT uk_server_targets_name UNIQUE (name)
);

CREATE TABLE monitoring_checks (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    server_id  BIGINT       NOT NULL,
    name       VARCHAR(100) NOT NULL,
    check_type VARCHAR(20)  NOT NULL,
    -- ICMP와 TCP는 host 또는 IP, HTTP와 HTTPS는 전체 URL이 들어갑니다.
    target     VARCHAR(500) NOT NULL,
    -- TCP Check에만 사용합니다. 나머지 Type은 NULL입니다.
    port       INTEGER      NULL,
    enabled    BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    -- 서버를 지우면 딸린 Check도 함께 지웁니다.
    -- Service에서도 같이 지우지만, 다른 경로로 지울 때를 대비한 안전장치입니다.
    CONSTRAINT fk_monitoring_checks_server FOREIGN KEY (server_id)
        REFERENCES server_targets (id) ON DELETE CASCADE
);

-- 서버 상세 화면에서 서버별 Check를 조회합니다.
CREATE INDEX ix_monitoring_checks_server_id ON monitoring_checks (server_id);

-- HTTP Service Discovery는 활성 Check만 조회합니다.
CREATE INDEX ix_monitoring_checks_enabled ON monitoring_checks (enabled);
